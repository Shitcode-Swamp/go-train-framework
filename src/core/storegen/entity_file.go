package storegen

import (
	"fmt"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	utils_strings "github.com/Shitcode-Swamp/go-train-framework/v3/src/utils/strings"
)

const (
	generatedHeader   = "// Code generated by go-train. DO NOT EDIT."
	filtersImportPath = "github.com/Shitcode-Swamp/go-train-framework/v3/src/core/persistance/filters"
	outputFileSuffix  = "_store.go"
	storeFieldsSuffix = "StoreFields"
)

type entityImport struct {
	alias string
	path  string
}

type storeField struct {
	name   string
	typ    string
	column string
}

type storeEntity struct {
	name     string
	typeName string
	fields   []storeField
}

func (e storeEntity) varName() string {
	return utils_strings.LowerFirst(e.name) + storeFieldsSuffix
}

func (e storeEntity) render(b *strings.Builder) {
	fmt.Fprintf(b, "var %s = struct {\n", e.varName())
	for _, f := range e.fields {
		fmt.Fprintf(b, "%s filters.Field[%s, %s]\n", f.name, e.typeName, f.typ)
	}
	b.WriteString("}{\n")
	for _, f := range e.fields {
		fmt.Fprintf(b, "%s: %s,\n", f.name, strconv.Quote(f.column))
	}
	b.WriteString("}\n")
}

type entityFile struct {
	sourcePath string
	pkg        string
	imports    []entityImport
	entities   []storeEntity
}

func newEntityFile(sourcePath, pkg string) *entityFile {
	return &entityFile{sourcePath: sourcePath, pkg: pkg}
}

func (f *entityFile) hasEntities() bool {
	return len(f.entities) > 0
}

func (f *entityFile) outputPath() string {
	return strings.TrimSuffix(f.sourcePath, filepath.Ext(f.sourcePath)) + outputFileSuffix
}

func (f *entityFile) render() string {
	b := strings.Builder{}
	b.WriteString(generatedHeader + "\n\n")
	fmt.Fprintf(&b, "package %s\n\n", f.pkg)
	b.WriteString("import (\n")
	for _, imp := range f.allImports() {
		fmt.Fprintf(&b, "%s %q\n", imp.alias, imp.path)
	}
	b.WriteString(")\n")
	for _, entity := range f.entities {
		b.WriteString("\n")
		entity.render(&b)
	}
	return b.String()
}

func (f *entityFile) allImports() []entityImport {
	imports := append([]entityImport{{alias: "filters", path: filtersImportPath}}, f.imports...)
	sort.Slice(imports, func(i, j int) bool { return imports[i].path < imports[j].path })
	return imports
}
