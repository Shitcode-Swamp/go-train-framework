package storegen

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func writeSource(t *testing.T, dir, name, src string) {
	t.Helper()
	if err := os.WriteFile(filepath.Join(dir, name), []byte(src), 0o644); err != nil {
		t.Fatalf("write %s: %v", name, err)
	}
}

func readGenerated(t *testing.T, dir, name string) string {
	t.Helper()
	content, err := os.ReadFile(filepath.Join(dir, name))
	if err != nil {
		t.Fatalf("read %s: %v", name, err)
	}
	return string(content)
}

func TestBuildGeneratesStoreFields(t *testing.T) {
	dir := t.TempDir()
	writeSource(t, dir, "product.go", `package entity

import (
	"time"

	"github.com/google/uuid"
)

// @Store("Product")
type Product struct {
	ID        uuid.UUID `+"`store:\"id,pk\"`"+`
	Name      string    `+"`store:\"name\"`"+`
	Price     float64   `+"`store:\"price\" json:\"price\"`"+`
	CreatedAt time.Time `+"`store:\"created_at\"`"+`
	Ignored   string    `+"`store:\"-\"`"+`
	Untagged  int
}

type NotAStore struct {
	Name string `+"`store:\"name\"`"+`
}
`)

	if err := NewStoreFieldsBuilder(dir).Build(); err != nil {
		t.Fatalf("Build: %v", err)
	}

	want := `// Code generated by go-train. DO NOT EDIT.

package entity

import (
	filters "github.com/Shitcode-Swamp/go-train-framework/v3/src/core/persistance/filters"
	uuid "github.com/google/uuid"
	time "time"
)

var productStoreFields = struct {
	ID        filters.Field[Product, uuid.UUID]
	Name      filters.Field[Product, string]
	Price     filters.Field[Product, float64]
	CreatedAt filters.Field[Product, time.Time]
}{
	ID:        "id",
	Name:      "name",
	Price:     "price",
	CreatedAt: "created_at",
}
`
	if got := readGenerated(t, dir, "product_store.go"); got != want {
		t.Errorf("generated file mismatch\n--- got ---\n%s\n--- want ---\n%s", got, want)
	}
}

func TestBuildSkipsFilesWithoutStoreAnnotation(t *testing.T) {
	dir := t.TempDir()
	writeSource(t, dir, "order.go", "package entity\n\ntype Order struct {\n\tID string `store:\"id\"`\n}\n")

	if err := NewStoreFieldsBuilder(dir).Build(); err != nil {
		t.Fatalf("Build: %v", err)
	}

	if _, err := os.Stat(filepath.Join(dir, "order_store.go")); !os.IsNotExist(err) {
		t.Errorf("expected no order_store.go, stat err: %v", err)
	}
}

func TestBuildUsesAnnotationNameAndGroupedTypeDecl(t *testing.T) {
	dir := t.TempDir()
	writeSource(t, dir, "user.go", "package entity\n\ntype (\n\t// @Store(UserAccount)\n\tUser struct {\n\t\tEmail string `store:\"email\"`\n\t}\n)\n")

	if err := NewStoreFieldsBuilder(dir).Build(); err != nil {
		t.Fatalf("Build: %v", err)
	}

	got := readGenerated(t, dir, "user_store.go")
	if !strings.Contains(got, "var userAccountStoreFields = struct {") {
		t.Errorf("expected userAccountStoreFields var, got:\n%s", got)
	}
	if !strings.Contains(got, "filters.Field[User, string]") {
		t.Errorf("expected field typed against User, got:\n%s", got)
	}
}

func TestBuildRefusesToOverwriteHandWrittenFile(t *testing.T) {
	dir := t.TempDir()
	writeSource(t, dir, "product.go", "package entity\n\n// @Store(\"Product\")\ntype Product struct {\n\tID string `store:\"id\"`\n}\n")
	writeSource(t, dir, "product_store.go", "package entity\n\ntype ProductStore struct{}\n")

	if err := NewStoreFieldsBuilder(dir).Build(); err == nil {
		t.Fatal("expected error when output file is hand-written")
	}
}

